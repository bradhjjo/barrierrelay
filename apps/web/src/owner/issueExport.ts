import type { Ticket } from '@barrierrelay/shared/src/schema';
import { environmentWords } from '../../../../packages/collector/src/environment';

const FOOTER = 'Generated by BarrierRelay; verification is a scoped client-side check, not WCAG certification.';
const MAX_URL = 7500;
const REMOVED = '[link removed]';
const TICKET_PATH = /[\\/]t[\\/][a-z0-9]{20}(?![a-z0-9])/;
const UUID_V4 = /\b[0-9a-f]{8}(?:-|%2d)[0-9a-f]{4}(?:-|%2d)4[0-9a-f]{3}(?:-|%2d)[89ab][0-9a-f]{3}(?:-|%2d)[0-9a-f]{12}\b/;
const PARAMETER = /\b(?:capture|ext)\s*=/;
const BARE_PARAMETER = /\b(?:capture|ext)\s*=\s*$/;
const PARAMETER_NAME = /\b(?:capture|ext)\s*$/;
const MAX_DECODE_ROUNDS = 10;
const PERCENT_ESCAPE = /%[\da-f]{2}/i;
const HTML_ENTITIES: Record<string, string> = {
  sol: '/', bsol: '\\', colon: ':', quest: '?', equals: '=',
  amp: '&', num: '#', period: '.', percnt: '%', lowbar: '_',
  lt: '<', gt: '>', quot: '"', apos: "'",
  tab: '\t', newline: '\n', nbsp: '\u00a0',
  zerowidthspace: '\u200b', zwj: '\u200d', zwnj: '\u200c', nobreak: '\u2060',
};

function canonicalize(value: string): string {
  return value.normalize('NFKC').replace(/\p{Default_Ignorable_Code_Point}/gu, '').replace(/[⁄∕]/g, '/');
}

function decodeEntities(value: string): string {
  return value.replace(/&(?:#(x[\da-f]+|\d+)|([a-z][a-z\d]*));/gi, (entity, numeric?: string, named?: string) => {
    if (named) {
      const key = named.toLowerCase();
      return Object.hasOwn(HTML_ENTITIES, key) ? HTML_ENTITIES[key] : entity;
    }
    if (!numeric) return entity;
    const hex = numeric[0].toLowerCase() === 'x';
    const codePoint = parseInt(hex ? numeric.slice(1) : numeric, hex ? 16 : 10);
    return codePoint > 0 && codePoint <= 0x10ffff && !(codePoint >= 0xd800 && codePoint <= 0xdfff)
      ? String.fromCodePoint(codePoint) : '\ufffd';
  });
}

// A null form means decoding could not safely reach a fixpoint.
function* decodedForms(value: string): Generator<string | null> {
  value = canonicalize(value);
  for (let round = 0; round < MAX_DECODE_ROUNDS; round++) {
    yield value.toLowerCase();
    let percentDecoded = value;
    if (PERCENT_ESCAPE.test(value)) {
      try {
        percentDecoded = decodeURIComponent(value);
      } catch {
        // An invalid escape must not mask decodable ASCII elsewhere in the value.
        percentDecoded = value.replace(/%[0-7][\da-f]/gi, hex => String.fromCharCode(parseInt(hex.slice(1), 16)));
      }
      percentDecoded = canonicalize(percentDecoded);
      if (percentDecoded !== value) yield percentDecoded.toLowerCase();
    }
    const entityDecoded = percentDecoded.includes('&') ? decodeEntities(percentDecoded) : percentDecoded;
    const decoded = entityDecoded === percentDecoded ? percentDecoded : canonicalize(entityDecoded);
    if (decoded === value) {
      if (PERCENT_ESCAPE.test(decoded)) yield null;
      return;
    }
    value = decoded;
  }
  yield value.toLowerCase();
  yield null;
}

// Ticket/owner links are bearer-like: exporting one can expose write access.
function isPrivate(value: string, ticketId: string): boolean {
  return TICKET_PATH.test(value) || PARAMETER.test(value) || UUID_V4.test(value)
    || (ticketId !== '' && value.includes(ticketId));
}

function containsPrivate(value: string, ticketId: string): boolean {
  for (const form of decodedForms(value)) {
    if (form === null || isPrivate(form, ticketId)) return true;
  }
  return false;
}

function publicText(value: string, ticketId: string): string {
  const tokens = value.trim().split(/\s+/);
  let followsName = false;
  let followsBareAssignment = false;
  for (let i = 0; i < tokens.length; i++) {
    let redact = followsBareAssignment;
    let endsName = false;
    let endsBareAssignment = false;
    for (const form of decodedForms(tokens[i])) {
      if (form === null) {
        redact = true;
        break;
      }
      redact ||= isPrivate(form, ticketId);
      endsName ||= PARAMETER_NAME.test(form);
      endsBareAssignment ||= BARE_PARAMETER.test(form);
      if (followsName && /^\s*=/.test(form)) {
        tokens[i - 1] = REMOVED;
        redact = true;
        endsBareAssignment ||= /^\s*=\s*$/.test(form);
      }
    }
    if (redact) tokens[i] = REMOVED;
    followsName = endsName;
    followsBareAssignment = endsBareAssignment;
  }
  return tokens.join(' ');
}

function escapeMarkdown(text: string): string {
  return text.replaceAll('&', '&amp;').replace(/[\\`*_[\]<>~]/g, '\\$&')
    .replace(/^[#=+|-]/, '\\$&')
    .replace(/^(\d+)([.)])/, '$1\\$2');
}

function publicUrl(raw: string, ticketId: string): string | null {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return null;
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') return null;
  const path = url.origin + url.pathname;
  return containsPrivate(raw, ticketId) || containsPrivate(path, ticketId) ? null : path;
}

function fence(code: string, ticketId: string): string {
  // Keep exported snippets verbatim; withhold the whole snippet if it contains private data.
  if (containsPrivate(code, ticketId)) return REMOVED;
  let length = 3;
  for (const run of code.matchAll(/`+|~+/g)) length = Math.max(length, run[0].length + 1);
  const delimiter = '`'.repeat(length);
  return `${delimiter}\n${code}\n${delimiter}`;
}

export function issueTitle(ticket: Ticket): string {
  return `[a11y] ${publicText(ticket.draft.summary, ticket.id.toLowerCase())}`.slice(0, 120);
}

export function issueMarkdown(ticket: Ticket): string {
  const ticketId = ticket.id.toLowerCase();
  const text = (value: string) => escapeMarkdown(publicText(value, ticketId));
  // Ignore query and fragment, but keep numeric entities intact for the privacy check.
  const pagePath = `${ticket.site.origin}${ticket.site.path}`.match(/^(?:&#(?:\d+|x[\da-f]+);|[^?#])*/i)![0];
  const page = publicUrl(pagePath, ticketId);
  const draft = ticket.draft;
  const lines = [
    `## ${text(draft.summary)}`, '', `**Page:** ${escapeMarkdown(page ?? REMOVED)}`, `**Status:** ${text(ticket.status)}`, '',
    '## Steps to reproduce', ...draft.stepsToReproduce.map((step, i) => `${i + 1}. ${text(step)}`), '',
    '## Expected', text(draft.expected), '', '## Actual', text(draft.actual), '',
  ];
  const plan = ticket.fixPlan;
  if (plan) {
    lines.push('## WCAG success criteria', ...plan.wcag.map(w => `- ${text(`WCAG ${w.sc}`)}: ${text(w.title)} (${w.level})`), '',
      '## Root cause', text(plan.rootCause), '', '## Suggested fix', text(plan.fix.description), '');
    if (plan.fix.codeBefore !== undefined) lines.push('### Before', fence(plan.fix.codeBefore, ticketId), '');
    lines.push('### After', fence(plan.fix.codeAfter, ticketId), '',
      '## Verification checklist', ...plan.verification.map(item => `- [ ] ${text(item)}`), '', '## Sources');
    let hasPublicSource = false;
    for (const source of plan.sources) {
      const url = publicUrl(source.url, ticketId);
      if (url) {
        lines.push(`- [${text(source.title)}](<${url.replaceAll('&', '&amp;')}>)`);
        hasPublicSource = true;
      }
    }
    if (!hasPublicSource) lines.push('No public grounding sources available.');
  } else lines.push('Fix plan not available yet.');
  const environment = ticket.sharedFacts.environment;
  if (environment) lines.push('', '## Environment', ...environmentWords(environment).map(value => `- ${text(value)}`), '');
  lines.push('', '## Assistive technology context', ...(ticket.sharedFacts.assistive.length
    ? ticket.sharedFacts.assistive.map(value => `- ${typeof value === 'string' ? text(value).replaceAll('-', ' ') : 'unrecognized value'}`)
    : ['Not specified.']), '');
  lines.push('', '**Please reply:** Please acknowledge this report on the ticket or leave a comment with your response and repair status.', '', '## Learn more');
  for (const [label, raw] of [
    ['Introduction to Web Accessibility', 'https://www.w3.org/WAI/fundamentals/accessibility-intro/'],
    ['Stories of Web Users', 'https://www.w3.org/WAI/people-use-web/user-stories/'],
    ['Web Content Accessibility Guidelines (WCAG)', 'https://www.w3.org/WAI/standards-guidelines/wcag/'],
  ]) {
    const url = publicUrl(raw, ticketId);
    if (url) lines.push(`- [${text(label)}](<${url.replaceAll('&', '&amp;')}>)`);
  }
  lines.push('', FOOTER);
  return lines.join('\n');
}

export function githubNewIssueUrl(repo: string, ticket: Ticket): string | null {
  repo = repo.trim();
  if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repo)) return null;
  if (repo.split('/').some(part => part === '.' || part === '..' || /^[a-z0-9]{20}$/i.test(part))
    || isPrivate(repo.toLowerCase(), ticket.id.toLowerCase())) return null;
  const makeUrl = (body: string) => `https://github.com/${repo}/issues/new?${new URLSearchParams({ title: issueTitle(ticket), body })}`;
  const full = makeUrl(issueMarkdown(ticket));
  if (full.length <= MAX_URL) return full;
  const shortened = makeUrl(`Paste the copied Markdown here using “Copy as GitHub issue”.\n\n${FOOTER}`);
  return shortened.length <= MAX_URL ? shortened : null;
}
